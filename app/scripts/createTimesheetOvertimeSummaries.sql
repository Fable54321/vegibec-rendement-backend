BEGIN;

CREATE SCHEMA IF NOT EXISTS timesheets;

CREATE TABLE IF NOT EXISTS timesheets.user_overtime_weeks (
  user_id integer NOT NULL,
  week_start date NOT NULL,
  total_minutes bigint NOT NULL DEFAULT 0,
  banked_minutes bigint NOT NULL DEFAULT 0,
  updated_at timestamp with time zone NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, week_start)
);

CREATE TABLE IF NOT EXISTS timesheets.user_overtime_totals (
  user_id integer PRIMARY KEY,
  total_banked_minutes bigint NOT NULL DEFAULT 0,
  updated_at timestamp with time zone NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS timesheets.public_holidays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  holiday_date date NOT NULL UNIQUE,
  name text NOT NULL,
  credited_minutes integer NOT NULL DEFAULT 480,
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamp with time zone NOT NULL DEFAULT NOW(),
  updated_at timestamp with time zone NOT NULL DEFAULT NOW(),
  CONSTRAINT public_holidays_credited_minutes_check
    CHECK (credited_minutes BETWEEN 0 AND 1440)
);

ALTER TABLE timesheets.user_overtime_weeks
  ADD COLUMN IF NOT EXISTS worked_minutes bigint NOT NULL DEFAULT 0;

ALTER TABLE timesheets.user_overtime_weeks
  ADD COLUMN IF NOT EXISTS holiday_minutes bigint NOT NULL DEFAULT 0;

-- Before holiday credits existed, total_minutes contained worked time only.
UPDATE timesheets.user_overtime_weeks
SET worked_minutes = total_minutes,
    holiday_minutes = 0
WHERE worked_minutes = 0
  AND holiday_minutes = 0
  AND total_minutes <> 0;

CREATE OR REPLACE FUNCTION timesheets.refresh_user_overtime_total(
  target_user_id integer
)
RETURNS void
LANGUAGE plpgsql
AS $function$
DECLARE
  calculated_total bigint;
  week_count bigint;
BEGIN
  SELECT
    COUNT(*)::bigint,
    COALESCE(SUM(ow.banked_minutes), 0)::bigint
  INTO week_count, calculated_total
  FROM timesheets.user_overtime_weeks ow
  WHERE ow.user_id = target_user_id;

  IF week_count = 0 THEN
    DELETE FROM timesheets.user_overtime_totals
    WHERE user_id = target_user_id;
    RETURN;
  END IF;

  INSERT INTO timesheets.user_overtime_totals (
    user_id,
    total_banked_minutes,
    updated_at
  )
  VALUES (target_user_id, calculated_total, NOW())
  ON CONFLICT (user_id)
  DO UPDATE SET
    total_banked_minutes = EXCLUDED.total_banked_minutes,
    updated_at = NOW();
END;
$function$;

CREATE OR REPLACE FUNCTION timesheets.refresh_user_overtime_week(
  target_user_id integer,
  target_week_start date
)
RETURNS void
LANGUAGE plpgsql
AS $function$
DECLARE
  calculated_worked_minutes bigint;
  calculated_holiday_minutes bigint;
  calculated_total bigint;
BEGIN
  SELECT GREATEST(
    0,
    COALESCE(
      SUM(
        COALESCE(
          ws.duration_minutes,
          ROUND(EXTRACT(EPOCH FROM ws.end_time - ws.start_time) / 60)
        ) - COALESCE(ws.lunch_duration, 0)
      ),
      0
    )
  )::bigint
  INTO calculated_worked_minutes
  FROM timesheets.work_sessions ws
  WHERE ws.user_id = target_user_id
    AND ws.end_time IS NOT NULL
    AND date_trunc(
      'week',
      ws.start_time AT TIME ZONE 'America/Toronto'
    )::date = target_week_start;

  SELECT COALESCE(SUM(ph.credited_minutes), 0)::bigint
  INTO calculated_holiday_minutes
  FROM timesheets.public_holidays ph
  WHERE ph.is_active = TRUE
    AND ph.holiday_date BETWEEN target_week_start AND target_week_start + 6
    AND (
      EXISTS (
        SELECT 1
        FROM public.users holiday_user
        WHERE holiday_user.id = target_user_id
          AND holiday_user.uses_worksheet = TRUE
          AND holiday_user.is_active = TRUE
          AND holiday_user.created_at::date <= ph.holiday_date
      )
      OR calculated_worked_minutes > 0
    )
    AND NOT EXISTS (
      SELECT 1
      FROM timesheets.work_sessions holiday_session
      WHERE holiday_session.user_id = target_user_id
        AND holiday_session.end_time IS NOT NULL
        AND (
          holiday_session.start_time AT TIME ZONE 'America/Toronto'
        )::date = ph.holiday_date
    );

  calculated_total :=
    calculated_worked_minutes + calculated_holiday_minutes;

  IF calculated_total = 0 THEN
    DELETE FROM timesheets.user_overtime_weeks
    WHERE user_id = target_user_id
      AND week_start = target_week_start;
    PERFORM timesheets.refresh_user_overtime_total(target_user_id);
    RETURN;
  END IF;

  INSERT INTO timesheets.user_overtime_weeks (
    user_id,
    week_start,
    worked_minutes,
    holiday_minutes,
    total_minutes,
    banked_minutes,
    updated_at
  )
  VALUES (
    target_user_id,
    target_week_start,
    calculated_worked_minutes,
    calculated_holiday_minutes,
    calculated_total,
    GREATEST(0, calculated_total - 2400),
    NOW()
  )
  ON CONFLICT (user_id, week_start)
  DO UPDATE SET
    worked_minutes = EXCLUDED.worked_minutes,
    holiday_minutes = EXCLUDED.holiday_minutes,
    total_minutes = EXCLUDED.total_minutes,
    banked_minutes = EXCLUDED.banked_minutes,
    updated_at = NOW();

  PERFORM timesheets.refresh_user_overtime_total(target_user_id);
END;
$function$;

CREATE OR REPLACE FUNCTION timesheets.sync_user_overtime_week()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
  old_week_start date;
  new_week_start date;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    old_week_start := date_trunc(
      'week',
      OLD.start_time AT TIME ZONE 'America/Toronto'
    )::date;
    PERFORM timesheets.refresh_user_overtime_week(
      OLD.user_id,
      old_week_start
    );
  END IF;

  IF TG_OP = 'INSERT' THEN
    new_week_start := date_trunc(
      'week',
      NEW.start_time AT TIME ZONE 'America/Toronto'
    )::date;
    PERFORM timesheets.refresh_user_overtime_week(
      NEW.user_id,
      new_week_start
    );
  ELSIF TG_OP = 'UPDATE' THEN
    new_week_start := date_trunc(
      'week',
      NEW.start_time AT TIME ZONE 'America/Toronto'
    )::date;

    IF NEW.user_id IS DISTINCT FROM OLD.user_id
      OR new_week_start IS DISTINCT FROM old_week_start THEN
      PERFORM timesheets.refresh_user_overtime_week(
        NEW.user_id,
        new_week_start
      );
    END IF;
  END IF;

  RETURN NULL;
END;
$function$;

DROP TRIGGER IF EXISTS sync_user_overtime_week
ON timesheets.work_sessions;

CREATE TRIGGER sync_user_overtime_week
AFTER INSERT OR DELETE OR UPDATE OF
  user_id,
  start_time,
  end_time,
  duration_minutes,
  lunch_duration
ON timesheets.work_sessions
FOR EACH ROW
EXECUTE FUNCTION timesheets.sync_user_overtime_week();

CREATE OR REPLACE FUNCTION timesheets.refresh_overtime_holiday_week(
  target_holiday_date date
)
RETURNS void
LANGUAGE plpgsql
AS $function$
DECLARE
  target_week_start date;
  affected_user_id integer;
BEGIN
  target_week_start := date_trunc('week', target_holiday_date)::date;

  FOR affected_user_id IN
    SELECT candidate.user_id
    FROM (
      SELECT u.id AS user_id
      FROM public.users u
      WHERE u.uses_worksheet = TRUE
        AND u.is_active = TRUE
        AND u.created_at::date <= target_holiday_date

      UNION

      SELECT ws.user_id
      FROM timesheets.work_sessions ws
      WHERE date_trunc(
        'week',
        ws.start_time AT TIME ZONE 'America/Toronto'
      )::date = target_week_start

      UNION

      SELECT ow.user_id
      FROM timesheets.user_overtime_weeks ow
      WHERE ow.week_start = target_week_start
    ) candidate
  LOOP
    PERFORM timesheets.refresh_user_overtime_week(
      affected_user_id,
      target_week_start
    );
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION timesheets.sync_public_holiday_overtime_weeks()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    PERFORM timesheets.refresh_overtime_holiday_week(OLD.holiday_date);
  END IF;

  IF TG_OP <> 'DELETE' AND (
    TG_OP = 'INSERT'
    OR NEW.holiday_date IS DISTINCT FROM OLD.holiday_date
    OR NEW.credited_minutes IS DISTINCT FROM OLD.credited_minutes
    OR NEW.is_active IS DISTINCT FROM OLD.is_active
  ) THEN
    PERFORM timesheets.refresh_overtime_holiday_week(NEW.holiday_date);
  END IF;

  RETURN NULL;
END;
$function$;

DROP TRIGGER IF EXISTS sync_public_holiday_overtime_weeks
ON timesheets.public_holidays;

CREATE TRIGGER sync_public_holiday_overtime_weeks
AFTER INSERT OR DELETE OR UPDATE OF
  holiday_date,
  credited_minutes,
  is_active
ON timesheets.public_holidays
FOR EACH ROW
EXECUTE FUNCTION timesheets.sync_public_holiday_overtime_weeks();

CREATE OR REPLACE FUNCTION timesheets.sync_user_holiday_overtime_weeks()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
  holiday record;
BEGIN
  FOR holiday IN
    SELECT ph.holiday_date
    FROM timesheets.public_holidays ph
    WHERE ph.holiday_date >= NEW.created_at::date
  LOOP
    PERFORM timesheets.refresh_user_overtime_week(
      NEW.id,
      date_trunc('week', holiday.holiday_date)::date
    );
  END LOOP;

  RETURN NULL;
END;
$function$;

DROP TRIGGER IF EXISTS sync_user_holiday_overtime_weeks
ON public.users;

CREATE TRIGGER sync_user_holiday_overtime_weeks
AFTER INSERT OR UPDATE OF uses_worksheet, is_active
ON public.users
FOR EACH ROW
EXECUTE FUNCTION timesheets.sync_user_holiday_overtime_weeks();

