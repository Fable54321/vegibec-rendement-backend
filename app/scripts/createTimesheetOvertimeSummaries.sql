-- Recalculate every week that already contains completed work. This is also
-- the backfill path when the migration is rerun after calculation changes.
DO $block$
DECLARE
  target record;
BEGIN
  FOR target IN
    SELECT ph.holiday_date
    FROM timesheets.public_holidays ph
  LOOP
    PERFORM timesheets.refresh_overtime_holiday_week(
      target.holiday_date
    );
  END LOOP;

  FOR target IN
    SELECT DISTINCT
      ws.user_id,
      date_trunc(
        'week',
        ws.start_time AT TIME ZONE 'America/Toronto'
      )::date AS week_start
    FROM timesheets.work_sessions ws
    WHERE ws.end_time IS NOT NULL
  LOOP
    PERFORM timesheets.refresh_user_overtime_week(
      target.user_id,
      target.week_start
    );
  END LOOP;
END;
$block$;

